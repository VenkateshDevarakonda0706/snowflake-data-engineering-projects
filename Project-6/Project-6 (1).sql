CREATE OR REPLACE TABLE DIM_REGION (
    REGION_ID NUMBER PRIMARY KEY,
    REGION_NAME VARCHAR(50)
);

CREATE OR REPLACE TABLE DIM_STATE (
    STATE_ID NUMBER PRIMARY KEY,
    STATE_NAME VARCHAR(50),
    REGION_ID NUMBER,

    FOREIGN KEY(REGION_ID) REFERENCES DIM_REGION(REGION_ID)
);

CREATE OR REPLACE TABLE DIM_CITY (
    CITY_ID NUMBER PRIMARY KEY,
    CITY_NAME VARCHAR(50),
    STATE_ID NUMBER,

    FOREIGN KEY(STATE_ID) REFERENCES DIM_STATE(STATE_ID)
);

INSERT INTO DIM_REGION (REGION_ID,REGION_NAME)
    SELECT 
        ROW_NUMBER() OVER (ORDER BY REGION_NAME) AS REGION_ID,
        REGION_NAME
    FROM (
        SELECT DISTINCT REGION AS REGION_NAME FROM DIM_BRANCH 
            WHERE REGION IS NOT NULL
);

SELECT * FROM DIM_REGION;

INSERT INTO DIM_STATE
    (STATE_ID, STATE_NAME, REGION_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY STATE_NAME) AS STATE_ID,
    STATE_NAME,
    REGION_ID
FROM (
    SELECT DISTINCT
        B.STATE AS STATE_NAME,
        R.REGION_ID
    FROM RETAIL_DB_P4.RETAIL.DIM_BRANCH B
    JOIN DIM_REGION R
        ON B.REGION = R.REGION_NAME
    WHERE B.STATE IS NOT NULL

    UNION

    SELECT 'Andhra Pradesh', 3
    UNION
    SELECT 'Bihar', 1
    UNION
    SELECT 'Chandigarh', 2
    UNION
    SELECT 'Madhya Pradesh', 2
);

SELECT * FROM DIM_STATE;

INSERT INTO DIM_CITY
    (CITY_ID, CITY_NAME, STATE_ID)
SELECT
    ROW_NUMBER() OVER (
        ORDER BY G.STATE_NAME, G.CITY_NAME
    ) AS CITY_ID,
    G.CITY_NAME,
    S.STATE_ID
FROM (
    SELECT DISTINCT
        CITY AS CITY_NAME,
        STATE AS STATE_NAME
    FROM RETAIL_DB_P4.RETAIL.DIM_BRANCH
    WHERE CITY IS NOT NULL
      AND STATE IS NOT NULL

    UNION

    SELECT DISTINCT
        CITY AS CITY_NAME,
        STATE AS STATE_NAME
    FROM RETAIL_DB_P4.RETAIL.DIM_CUSTOMER
    WHERE CITY IS NOT NULL
      AND STATE IS NOT NULL
) G
JOIN DIM_STATE S
    ON G.STATE_NAME = S.STATE_NAME;

SELECT * FROM DIM_CITY;


CREATE OR REPLACE TABLE DIM_CATEGORY (
    CATEGORY_ID NUMBER PRIMARY KEY,
    CATEGORY_NAME VARCHAR(50)
);

CREATE OR REPLACE TABLE DIM_BRAND (
    BRAND_ID NUMBER PRIMARY KEY,
    BRAND_NAME VARCHAR(50),
    CATEGORY_ID NUMBER,

    FOREIGN KEY(CATEGORY_ID) REFERENCES DIM_CATEGORY(CATEGORY_ID)
);

INSERT INTO DIM_CATEGORY (CATEGORY_ID,CATEGORY_NAME)
    SELECT
        DENSE_RANK() OVER (ORDER BY CATEGORY_NAME) AS CATEGORY_ID,
        CATEGORY_NAME
    FROM (
        SELECT DISTINCT CATEGORY AS CATEGORY_NAME
        FROM DIM_PRODUCT WHERE CATEGORY IS NOT NULL
);

SELECT * FROM DIM_CATEGORY;

INSERT INTO DIM_BRAND (BRAND_ID,BRAND_NAME,CATEGORY_ID)
    SELECT 
        ROW_NUMBER() OVER (ORDER BY P.BRAND_NAME,P.CATEGORY) AS BRAND_ID,
        P.BRAND_NAME,
        C.CATEGORY_ID
    FROM (
        SELECT DISTINCT BRAND AS BRAND_NAME,CATEGORY FROM DIM_PRODUCT
        WHERE BRAND IS NOT NULL AND CATEGORY IS NOT NULL
    ) AS P
    JOIN DIM_CATEGORY AS C
    ON C.CATEGORY_NAME=P.CATEGORY
;

SELECT * FROM DIM_BRAND;

CREATE OR REPLACE TABLE DIM_YEAR (
    YEAR_ID NUMBER PRIMARY KEY,
    YEAR NUMBER
);

INSERT INTO DIM_YEAR (YEAR_ID,YEAR)
    SELECT
        ROW_NUMBER() OVER (ORDER BY YEAR) AS YEAR_ID,
        YEAR
    FROM (
        SELECT DISTINCT YEAR FROM DIM_DATE WHERE YEAR IS NOT NULL
    )
;

SELECT * FROM DIM_YEAR;

CREATE OR REPLACE TABLE DIM_QUARTER (
    QUARTER_ID NUMBER PRIMARY KEY,
    QUARTER VARCHAR(10),
    YEAR_ID NUMBER,

    FOREIGN KEY(YEAR_ID) REFERENCES DIM_YEAR(YEAR_ID)
);

INSERT INTO DIM_QUARTER (QUARTER_ID,QUARTER,YEAR_ID)
    SELECT
        ROW_NUMBER() OVER (ORDER BY D.QUARTER) AS QUARTER_ID,
        D.QUARTER,
        Y.YEAR_ID
    FROM (
        SELECT DISTINCT QUARTER,YEAR FROM DIM_DATE
        WHERE QUARTER IS NOT NULL AND YEAR IS NOT NULL
    ) AS D
    JOIN DIM_YEAR AS Y
    ON D.YEAR=Y.YEAR
;

SELECT * FROM DIM_QUARTER;

CREATE OR REPLACE TABLE DIM_MONTH (
    MONTH_ID NUMBER PRIMARY KEY,
    MONTH VARCHAR(30),
    QUARTER_ID NUMBER,
    
    FOREIGN KEY (QUARTER_ID) REFERENCES DIM_QUARTER(QUARTER_ID)
);

INSERT INTO DIM_MONTH (MONTH_ID,MONTH,QUARTER_ID)
    SELECT 
        ROW_NUMBER() OVER (ORDER BY D.YEAR, D.QUARTER, D.MONTH) AS MONTH_ID,
        D.MONTH,
        Q.QUARTER_ID
    FROM (
        SELECT DISTINCT MONTH,QUARTER,YEAR FROM DIM_DATE
        WHERE MONTH IS NOT NULL
            AND QUARTER IS NOT NULL
            AND YEAR IS NOT NULL
    ) AS D
    JOIN DIM_YEAR AS Y
        ON Y.YEAR=D.YEAR
    JOIN DIM_QUARTER AS Q
        ON D.QUARTER=Q.QUARTER
        AND Q.YEAR_ID=Y.YEAR_ID
;    

SELECT * FROM DIM_MONTH;

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_ID NUMBER PRIMARY KEY,
    PRODUCT_NAME VARCHAR(50),
    BRAND_ID NUMBER,
    PRICE NUMBER,

    FOREIGN KEY(BRAND_ID) REFERENCES DIM_BRAND(BRAND_ID)
