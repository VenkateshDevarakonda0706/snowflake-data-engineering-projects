--Top 10 Customers
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(F.TOTAL_AMOUNT) AS CUSTOMER_REVENUE,
    DENSE_RANK() OVER (
        ORDER BY SUM(F.TOTAL_AMOUNT) DESC
    ) AS CUSTOMER_RANK
