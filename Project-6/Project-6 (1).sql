SELECT * FROM DIM_CUSTOMER;

CREATE OR REPLACE TABLE DIM_BRANCH (
    BRANCH_ID NUMBER PRIMARY KEY,
    BRANCH_NAME VARCHAR(30),
    CITY_ID NUMBER,
    MANAGER_NAME VARCHAR(50),

    FOREIGN KEY (CITY_ID) REFERENCES DIM_CITY(CITY_ID)
);

INSERT INTO DIM_BRANCH (BRANCH_ID,BRANCH_NAME,CITY_ID,MANAGER_NAME)
SELECT 
    B.BRANCH_ID,
    B.BRANCH_NAME,
    C.CITY_ID,
    B.MANAGER_NAME
FROM RETAIL_DB_P4.RETAIL.DIM_BRANCH AS B 
JOIN DIM_REGION AS R 
    ON B.REGION=R.REGION_NAME
JOIN DIM_STATE AS S 
    ON B.STATE=S.STATE_NAME
    AND R.REGION_ID=S.REGION_ID
JOIN DIM_CITY AS C
    ON B.CITY=C.CITY_NAME
    AND S.STATE_ID=C.STATE_ID
;

SELECT * FROM DIM_BRANCH;

---Full geography drill-down
SELECT
    R.REGION_NAME,
    S.STATE_NAME,
    C.CITY_NAME,
    COUNT(DISTINCT B.BRANCH_ID) AS BRANCH_COUNT,
    COUNT(DISTINCT CU.CUSTOMER_ID) AS CUSTOMER_COUNT
FROM DIM_REGION R
JOIN DIM_STATE S
    ON R.REGION_ID = S.REGION_ID
JOIN DIM_CITY C
    ON S.STATE_ID = C.STATE_ID
LEFT JOIN DIM_BRANCH B
    ON C.CITY_ID = B.CITY_ID
LEFT JOIN DIM_CUSTOMER CU
    ON C.CITY_ID = CU.CITY_ID
GROUP BY
    R.REGION_NAME,
    S.STATE_NAME,
    C.CITY_NAME
ORDER BY
    R.REGION_NAME,
    S.STATE_NAME,
    C.CITY_NAME;

--Product hierarchy
SELECT
    C.CATEGORY_NAME,
    B.BRAND_NAME,
    COUNT(P.PRODUCT_ID) AS PRODUCT_COUNT
FROM DIM_CATEGORY C
JOIN DIM_BRAND B
    ON C.CATEGORY_ID = B.CATEGORY_ID
JOIN DIM_PRODUCT P
    ON B.BRAND_ID = P.BRAND_ID
GROUP BY
    C.CATEGORY_NAME,
    B.BRAND_NAME
ORDER BY
    C.CATEGORY_NAME,
    B.BRAND_NAME;

--Date hierarchy
SELECT
    Y.YEAR,
    Q.QUARTER,
    M.MONTH,
    COUNT(D.DATE_ID) AS DATE_COUNT
FROM DIM_YEAR Y
JOIN DIM_QUARTER Q
    ON Y.YEAR_ID = Q.YEAR_ID
JOIN DIM_MONTH M
    ON Q.QUARTER_ID = M.QUARTER_ID
JOIN DIM_DATE D
    ON M.MONTH_ID = D.MONTH_ID
GROUP BY
    Y.YEAR,
    Q.QUARTER,
    M.MONTH
ORDER BY
    Y.YEAR,
    Q.QUARTER,
    M.MONTH;

--Customer-wise Sales Report
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    CI.CITY_NAME,
    S.STATE_NAME,
    R.REGION_NAME,
    SUM(F.TOTAL_AMOUNT) AS CUSTOMER_REVENUE
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
JOIN DIM_CITY CI
    ON C.CITY_ID = CI.CITY_ID
JOIN DIM_STATE S
    ON CI.STATE_ID = S.STATE_ID
