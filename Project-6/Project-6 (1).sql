    ON P.CATEGORY = C.CATEGORY_NAME
JOIN RETAIL_DB_P4.RETAIL_P6.DIM_BRAND AS B
    ON P.BRAND = B.BRAND_NAME
   AND C.CATEGORY_ID = B.CATEGORY_ID
;

SELECT * FROM DIM_PRODUCT;

CREATE OR REPLACE TABLE DIM_DATE (
    DATE_ID NUMBER PRIMARY KEY,
    DATE DATE,
    DAY NUMBER,
    DAY_NAME VARCHAR(30),
    WEEK_NO NUMBER,
    MONTH_ID NUMBER,
    IS_WEEKEND BOOLEAN,
    FOREIGN KEY (MONTH_ID) REFERENCES DIM_MONTH(MONTH_ID)
);

INSERT INTO DIM_DATE (DATE_ID,DATE,DAY,DAY_NAME,WEEK_NO,MONTH_ID,IS_WEEKEND)
SELECT
    D.DATE_ID,D.DATE,D.DAY,D.DAY_NAME,D.WEEK_NO,M.MONTH_ID,D.IS_WEEKEND
FROM RETAIL_DB_P4.RETAIL.DIM_DATE AS D
JOIN DIM_YEAR AS Y
    ON D.YEAR=Y.YEAR
JOIN DIM_QUARTER AS Q
    ON Q.QUARTER=D.QUARTER
    AND Q.YEAR_ID=Y.YEAR_ID
JOIN DIM_MONTH AS M
    ON M.MONTH=D.MONTH
    AND M.QUARTER_ID=Q.QUARTER_ID
;

SELECT * FROM DIM_DATE;

CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_ID NUMBER PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(50),
    CITY_ID NUMBER,
    MEMBERSHIP VARCHAR(10),

    FOREIGN KEY(CITY_ID) REFERENCES DIM_CITY(CITY_ID)
