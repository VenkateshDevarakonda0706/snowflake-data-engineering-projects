--Product Performance Dashboard
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    B.BRAND_NAME,
    C.CATEGORY_NAME,
    SUM(F.QUANTITY) AS QUANTITY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS PRODUCT_REVENUE,
    AVG(F.TOTAL_AMOUNT) AS AVG_SALE_VALUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRAND B
    ON P.BRAND_ID = B.BRAND_ID
JOIN DIM_CATEGORY C
    ON B.CATEGORY_ID = C.CATEGORY_ID
GROUP BY
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    B.BRAND_NAME,
    C.CATEGORY_NAME
ORDER BY
    PRODUCT_REVENUE DESC;

--Regional Sales Dashboard
SELECT
    R.REGION_NAME,
    SUM(F.QUANTITY) AS QUANTITY_SOLD,
    SUM(F.TOTAL_AMOUNT) AS REGION_REVENUE,
    COUNT(DISTINCT F.SALE_ID) AS SALES_COUNT,
    COUNT(DISTINCT B.BRANCH_ID) AS ACTIVE_BRANCHES
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
JOIN DIM_CITY CI
    ON B.CITY_ID = CI.CITY_ID
JOIN DIM_STATE S
    ON CI.STATE_ID = S.STATE_ID
JOIN DIM_REGION R
    ON S.REGION_ID = R.REGION_ID
GROUP BY R.REGION_NAME
ORDER BY REGION_REVENUE DESC;