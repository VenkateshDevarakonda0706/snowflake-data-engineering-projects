SELECT * FROM DIM_CUSTOMER_TYPE1;

CREATE OR REPLACE TABLE CUSTOMER_UPDATES
(
    CUSTOMER_ID    NUMBER,
    CUSTOMER_NAME  VARCHAR(100),
    CITY           VARCHAR(50),
    STATE          VARCHAR(50),
    MEMBERSHIP     VARCHAR(30),
    SEGMENT        VARCHAR(30),
    EFFECTIVE_DATE DATE
);

LIST @CUSTOMER_STAGE;

COPY INTO CUSTOMER_UPDATES
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE
)
FROM
(
    SELECT
        $1::NUMBER,
        $2::VARCHAR(100),
        $3::VARCHAR(50),
        $4::VARCHAR(50),
        $5::VARCHAR(30),
        $6::VARCHAR(30),
        $7::DATE
    FROM @CUSTOMER_STAGE/customer_updates.csv
)
FILE_FORMAT = (
    FORMAT_NAME = 'CUSTOMER_CSV_FORMAT'
);

SELECT * FROM CUSTOMER_UPDATES;

UPDATE DIM_CUSTOMER_TYPE1 AS TARGET
SET
    CUSTOMER_NAME = SOURCE.CUSTOMER_NAME,
    CITY          = SOURCE.CITY,
    STATE         = SOURCE.STATE,
    MEMBERSHIP    = SOURCE.MEMBERSHIP,
    SEGMENT       = SOURCE.SEGMENT
FROM CUSTOMER_UPDATES AS SOURCE
WHERE TARGET.CUSTOMER_ID = SOURCE.CUSTOMER_ID;

SELECT * FROM DIM_CUSTOMER_TYPE1 ORDER BY CUSTOMER_ID;

SELECT COUNT(*) AS TOTAL_RECORDS FROM DIM_CUSTOMER_TYPE1;

SELECT
    CUSTOMER_ID,
    CITY,
    STATE,
    MEMBERSHIP
FROM DIM_CUSTOMER_TYPE1
WHERE CUSTOMER_ID = 101;

