(
    CUSTOMER_KEY   NUMBER AUTOINCREMENT,
    CUSTOMER_ID    NUMBER,
    CUSTOMER_NAME  VARCHAR(100),
    CITY           VARCHAR(50),
    STATE          VARCHAR(50),
    MEMBERSHIP     VARCHAR(30),
    SEGMENT        VARCHAR(30),
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE    DATE,
    IS_CURRENT     BOOLEAN
);

DESC TABLE DIM_CUSTOMER_TYPE2;

INSERT INTO DIM_CUSTOMER_TYPE2
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
