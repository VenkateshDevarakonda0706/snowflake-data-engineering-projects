    $6::VARCHAR(30),
    '2026-01-01'::DATE,
    '9999-12-31'::DATE,
    TRUE
FROM @CUSTOMER_STAGE/customers_initial.csv
(
    FILE_FORMAT => 'CUSTOMER_CSV_FORMAT'
);

SELECT * FROM DIM_CUSTOMER_TYPE2;

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(IS_CURRENT) AS CURRENT_RECORDS
FROM DIM_CUSTOMER_TYPE2;

UPDATE DIM_CUSTOMER_TYPE2 AS TARGET
SET
    EXPIRY_DATE = DATEADD(DAY, -1, SOURCE.EFFECTIVE_DATE),
    IS_CURRENT  = FALSE
FROM CUSTOMER_UPDATES AS SOURCE
WHERE TARGET.CUSTOMER_ID = SOURCE.CUSTOMER_ID
  AND TARGET.IS_CURRENT = TRUE;

