CREATE TABLE DIM_CUSTOMER_HYBRID
(
    CUSTOMER_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR,
    CITY VARCHAR,
    PREVIOUS_CITY VARCHAR,
    STATE VARCHAR,
    CURRENT_MEMBERSHIP VARCHAR,
    PREVIOUS_MEMBERSHIP VARCHAR,
    HISTORICAL_MEMBERSHIP VARCHAR,
    SEGMENT VARCHAR,
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE DATE,
    IS_CURRENT BOOLEAN
);

DESC TABLE DIM_CUSTOMER_HYBRID;

LIST @RAW_STAGE;

COPY INTO DIM_CUSTOMER_HYBRID
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
FROM
(
    SELECT
        $1::NUMBER,
        $2::VARCHAR,
        $3::VARCHAR,
        NULL,
        $4::VARCHAR,
        $5::VARCHAR,
        NULL,
        $5::VARCHAR,
        $6::VARCHAR,
        '2026-01-01',
        '9999-12-31',
        TRUE
    FROM @RAW_STAGE/customers_initial.csv
);

SELECT COUNT(*) AS TOTAL_RECORDS FROM DIM_CUSTOMER_HYBRID;

SELECT COUNT(*) AS CURRENT_RECORDS FROM DIM_CUSTOMER_HYBRID WHERE IS_CURRENT = TRUE;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
FROM DIM_CUSTOMER_HYBRID
ORDER BY CUSTOMER_ID;

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(IS_CURRENT = TRUE) AS CURRENT_RECORDS,
    COUNT_IF(IS_CURRENT = FALSE) AS HISTORICAL_RECORDS
FROM DIM_CUSTOMER_HYBRID;

UPDATE DIM_CUSTOMER_HYBRID
SET
    EXPIRY_DATE = DATEADD(DAY, -1, UPD.$7),
    IS_CURRENT = FALSE
FROM @RAW_STAGE/customer_updates.csv AS UPD
WHERE CUSTOMER_ID = UPD.$1
  AND IS_CURRENT = TRUE;

